import { writeFile, mkdir } from "node:fs/promises";
import { computeWinding } from "../src/domain/winding.js";
import { computeSpectrum } from "../src/domain/spectrum.js";
import { computeInductance } from "../src/domain/inductance.js";

// These expected results come from the independently tested JavaScript model.
// Scilab executes its own implementation; it never calls JavaScript at runtime.
const phases = ["A", "B", "C"];
const cases = new Map();
function add(Q, p, layers, span = 0) {
  if (p >= 1 && p <= Math.floor(Q / 2)) cases.set([Q, p, layers, span].join("-"), { Q, p, layers, span });
}
add(12, 1, 1, 6);
add(12, 1, 1);
add(36, 2, 1);
add(12, 5, 2, 1);
add(9, 4, 2, 1);
add(18, 2, 1);
for (const Q of [6, 9, 12, 18, 24, 36, 60, 120]) {
  for (const p of new Set([1, 2, 4, 5, Math.floor(Q / 6), Math.floor(Q / 2) - 1])) {
    for (const layers of [1, 2]) add(Q, p, layers);
  }
}
for (const [Q, p] of [[12, 1], [12, 5], [24, 2], [36, 2], [120, 50]]) {
  for (const layers of [1, 2]) add(Q, p, layers, Math.floor(Q / 2));
}
add(120, 50, 2, 1);

const scalar = (value) => value == null ? "[]" : !Number.isFinite(value) ? "%nan" : String(value);
const quote = (value) => `"${value.replaceAll('"', '""')}"`;
const matrix = (rows) => rows.length ? `[${rows.map((row) => row.map(scalar).join(",")).join(";")}]` : "[]";
const vector = (values) => matrix(values.map((value) => [value]));
const lines = ["// Generated by scripts/generate-scilab-fixtures.mjs. Do not edit.", "ew_reference_cases = list();"];
let validCount = 0;
for (const { Q, p, layers, span } of cases.values()) {
  const w = computeWinding({ slots: Q, polePairs: p, layers, coilSpan: span || "auto" });
  const fields = {
    label: quote(`Q${Q}/p${p}/L${layers}/y${span || "auto"}`),
    input: matrix([[Q, p, layers, span]]),
    valid: w.valid ? "%t" : "%f",
    balanced: w.balanced ? "%t" : "%f",
    coilSpan: scalar(w.coilSpan),
    kw: vector(w.phases.map((phase) => phase.kw)),
    phaseAngles: vector(w.phases.map((phase) => phase.angleDeg)),
    sides: matrix(w.slotLayers.map((side) => [side.slot, side.layer, phases.indexOf(side.phase) + 1, side.sign])),
    coils: matrix(w.coils.map((coil) => [phases.indexOf(coil.phase) + 1, coil.positiveSlot, coil.negativeSlot, coil.span, coil.positiveLayer, coil.negativeLayer, coil.direction])),
  };
  if (w.valid) {
    validCount += 1;
    const spectra = phases.map((phase) => computeSpectrum(w, { phase, maxOrder: 20 }));
    const ind = computeInductance(w, { maxOrder: 20, sampleCount: 16, selectedOrder: p });
    Object.assign(fields, {
      spectrumRaw: matrix(spectra[0].coefficients.map((_, k) => spectra.flatMap((s) => [s.coefficients[k].rawReal, s.coefficients[k].rawImag]))),
      spectrumRelative: matrix(spectra[0].coefficients.map((c) => [c.real, c.imag, c.amplitude])),
      fundamentalA: matrix([[spectra[0].fundamental.rawReal, spectra[0].fundamental.rawImag, spectra[0].fundamental.amplitude]]),
      matrixH: matrix(ind.matrixH),
      harmonicMatrixH: matrix(ind.harmonicMatrixH),
      fundamentalMatrixH: matrix(ind.fundamentalMatrixH),
      flux: vector(phases.map((phase) => ind.fluxLinkagesWbTurns[phase])),
      energyJ: scalar(ind.energyJ),
    });
  }
  lines.push(`ew_reference_cases($+1) = struct(${Object.entries(fields).map(([key, value]) => `${quote(key)},${value}`).join(", ..\n    ")});`);
}
await mkdir(new URL("../scilab/tests/", import.meta.url), { recursive: true });
await writeFile(new URL("../scilab/tests/reference-fixtures.sce", import.meta.url), lines.join("\n") + "\n");
console.log(`${cases.size} Scilab reference cases generated (${validCount} valid windings).`);
